std::string encodeCharset(const std::string& charsetName, std::string_view unicodeInput) {
    if (charsetName.empty() || charsetName == CHARSET_UNICODE) {
        return std::string(unicodeInput);
    }
    const auto& defs = getCharsetDefinitions();
    auto it = defs.find(resolveCharsetKey(charsetName));
    if (it == defs.end()) {
        return std::string(unicodeInput);
    }
    const auto& cs = it->second;
    std::u32string u32 = utf8ToU32(unicodeInput);
    std::string output;
    output.reserve(unicodeInput.size() * 2);
    for (char32_t chr : u32) {
        auto cit = cs.find(chr);
        if (cit != cs.end()) {
            output.append(cit->second);
        } else {
            output.append(u32CharToUtf8(chr));
        }
    }
    return output;
}

std::string decodeCharset(const std::string& charsetName, std::string_view encodedInput) {
    if (charsetName.empty() || charsetName == CHARSET_UNICODE) {
        return std::string(encodedInput);
    }
    const auto& defs = getCharsetDefinitions();
    auto it = defs.find(resolveCharsetKey(charsetName));
    if (it == defs.end()) {
        return std::string(encodedInput);
    }
    const auto& cs = it->second;

    // Build reverse lookup pairs sorted by encoded token length descending (greedy match).
    // For TCVN3, lowercase and uppercase share some accented vowel codes; prefer lowercase by default.
    std::vector<std::pair<std::string, char32_t>> rev;
    rev.reserve(cs.size());
    for (const auto& [cp, tok] : cs) {
        if (tok.empty()) continue;
        rev.emplace_back(tok, cp);
    }
    std::sort(rev.begin(), rev.end(), [](const auto& a, const auto& b) {
        if (a.first.size() != b.first.size()) {
            return a.first.size() > b.first.size();
        }
        // Prefer lowercase when tokens are identical (e.g. TCVN3)
        bool aLower = !isUpperChar(a.second);
        bool bLower = !isUpperChar(b.second);
        if (aLower != bLower) return aLower;
        return a.second < b.second;
    });

    std::string output;
    output.reserve(encodedInput.size());
    size_t i = 0;
    const size_t n = encodedInput.size();
    while (i < n) {
        bool matched = false;
        for (const auto& [tok, cp] : rev) {
            if (i + tok.size() <= n && encodedInput.substr(i, tok.size()) == tok) {
                output.append(u32CharToUtf8(cp));
                i += tok.size();
                matched = true;
                break;
            }
        }
        if (!matched) {
            output.push_back(encodedInput[i]);
            ++i;
        }
    }
    return output;
}

std::string removeVietnameseDiacritics(std::string_view unicodeInput) {
    std::u32string u32 = utf8ToU32(unicodeInput);
    std::u32string out;
    out.reserve(u32.size());
    for (char32_t c : u32) {
        bool upper = isUpperChar(c);
        char32_t lower = toLowerChar(c);
        char32_t base = addMarkToChar(addToneToChar(lower, 0), 0);
        out.push_back(upper ? toUpperChar(base) : base);
    }
    return u32ToUtf8(out);
}

std::string convertCharset(
    const std::string& fromCharset,
    const std::string& toCharset,
    std::string_view input,
    bool stripDiacritics) {
    std::string unicode = decodeCharset(fromCharset, input);
    if (stripDiacritics) {
        unicode = removeVietnameseDiacritics(unicode);
    }
    return encodeCharset(toCharset, unicode);
}

